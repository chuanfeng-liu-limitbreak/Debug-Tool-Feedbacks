async function refreshFeedback() {
  elements.loadingState.hidden = false;
  elements.feedbackList.hidden = true;
  elements.emptyState.hidden = true;

  try {
    state.feedback = await state.backend.listFeedback(state.userId);
    renderFeedback();
  } catch (error) {
    console.error(error);
    showToast(t("genericError"));
  } finally {
    elements.loadingState.hidden = true;
  }
}

function sortedFeedback() {
  const items = state.feedback.filter((item) => item.kind === state.activeType);
  if (elements.sortSelect.value === "new") {
    return items.sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt));
  }

  return items.sort((a, b) => {
    if (b.upvoteCount !== a.upvoteCount) {
      return b.upvoteCount - a.upvoteCount;
    }
    if (a.downvoteCount !== b.downvoteCount) {
      return a.downvoteCount - b.downvoteCount;
    }
    return new Date(b.createdAt) - new Date(a.createdAt);
  });
}

function renderFeedback() {
  if (!elements.feedbackView || elements.feedbackView.hidden) {
    return;
  }

  elements.feedbackList.replaceChildren();
  const items = sortedFeedback();
  elements.emptyState.hidden = items.length !== 0;
  elements.feedbackList.hidden = items.length === 0;

  items.forEach((item) => {
    const article = document.createElement("article");
    article.className = "feedback-item";

    const voteControls = document.createElement("div");
    voteControls.className = "vote-controls";

    const upvoteButton = document.createElement("button");
    upvoteButton.className = `vote-button is-upvote${item.userVote === 1 ? " is-selected" : ""}`;
    upvoteButton.type = "button";
    upvoteButton.setAttribute("aria-pressed", String(item.userVote === 1));
    upvoteButton.setAttribute(
      "aria-label",
      `${t(item.userVote === 1 ? "removeUpvoteFor" : "upvoteFor")} ${item.description}. ${item.upvoteCount} ${t("upvoteCountLabel")}`,
    );

    const upvoteSymbol = document.createElement("span");
    upvoteSymbol.className = "vote-symbol";
    upvoteSymbol.textContent = "↑";

    const upvoteCount = document.createElement("span");
    upvoteCount.className = "vote-count";
    upvoteCount.textContent = item.upvoteCount.toLocaleString();
    upvoteButton.append(upvoteSymbol, upvoteCount);

    const downvoteButton = document.createElement("button");
    downvoteButton.className = `vote-button is-downvote${item.userVote === -1 ? " is-selected" : ""}`;
    downvoteButton.type = "button";
    downvoteButton.setAttribute("aria-pressed", String(item.userVote === -1));
    downvoteButton.setAttribute(
      "aria-label",
      `${t(item.userVote === -1 ? "removeDownvoteFor" : "downvoteFor")} ${item.description}. ${item.downvoteCount} ${t("downvoteCountLabel")}`,
    );

    const downvoteSymbol = document.createElement("span");
    downvoteSymbol.className = "vote-symbol";
    downvoteSymbol.textContent = "↓";

    const downvoteCount = document.createElement("span");
    downvoteCount.className = "vote-count";
    downvoteCount.textContent = item.downvoteCount.toLocaleString();
    downvoteButton.append(downvoteSymbol, downvoteCount);

    const voteButtons = [upvoteButton, downvoteButton];
    upvoteButton.addEventListener("click", () => handleVote(item, 1, voteButtons));
    downvoteButton.addEventListener("click", () => handleVote(item, -1, voteButtons));
    voteControls.append(upvoteButton, downvoteButton);

    const content = document.createElement("div");
    content.className = "feedback-content";

    const copyRow = document.createElement("div");
    copyRow.className = "feedback-copy-row";

    const description = document.createElement("h2");
    description.className = "feedback-copy";
    description.textContent = item.description;

    const author = document.createElement("span");
    author.className = "feedback-author";
    author.textContent = `${t("by")} ${item.authorNickname}`;

    const meta = document.createElement("div");
    meta.className = "feedback-meta";
    meta.append(author);

    if (item.isOwner || state.isAdmin) {
      const deleteButton = document.createElement("button");
      deleteButton.className = "delete-feedback-button";
      deleteButton.type = "button";
      deleteButton.textContent = t("deleteFeedback");
      deleteButton.setAttribute(
        "aria-label",
        `${t("deleteFeedbackLabel")}: ${item.description}`,
      );
      deleteButton.addEventListener("click", () => handleDeleteFeedback(item, deleteButton));
      meta.append(deleteButton);
    }

    copyRow.append(description, meta);
    content.append(copyRow);
    article.append(voteControls, content);
    elements.feedbackList.append(article);
  });
}

async function handleVote(item, selectedValue, buttons) {
  const nextValue = item.userVote === selectedValue ? 0 : selectedValue;
  buttons.forEach((button) => {
    button.disabled = true;
  });

  try {
    await state.backend.setVote(item.id, state.userId, nextValue);
    if (item.userVote === 1) {
      item.upvoteCount -= 1;
    } else if (item.userVote === -1) {
      item.downvoteCount -= 1;
    }
    if (nextValue === 1) {
      item.upvoteCount += 1;
    } else if (nextValue === -1) {
      item.downvoteCount += 1;
    }
    item.userVote = nextValue;
    renderFeedback();
    const notificationKey =
      nextValue === 0 ? "voteRemoved" : nextValue === 1 ? "upvoteAdded" : "downvoteAdded";
    showToast(t(notificationKey));
  } catch (error) {
    console.error(error);
    showToast(t("genericError"));
    buttons.forEach((button) => {
      button.disabled = false;
    });
  }
}

async function handleDeleteFeedback(item, button) {
  if ((!item.isOwner && !state.isAdmin) || !window.confirm(t("deleteConfirmation"))) {
    return;
  }

  button.disabled = true;
  try {
    await state.backend.deleteFeedback(item.id, state.userId, state.isAdmin);
    state.feedback = state.feedback.filter(
      (candidate) => String(candidate.id) !== String(item.id),
    );
    renderFeedback();
    showToast(t("feedbackDeleted"));
  } catch (error) {
    console.error(error);
    showToast(t("genericError"));
    button.disabled = false;
  }
}

