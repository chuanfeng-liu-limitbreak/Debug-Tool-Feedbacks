async function initialize() {
  state.backend = isSupabaseConfigured() ? createSupabaseBackend() : createLocalBackend();
  bindEvents();
  applyLanguage(state.language);

  try {
    const hasAccess = await state.backend.hasAccess();
    if (!hasAccess) {
      showAccessView();
      return;
    }

    await continueAfterAccess();
    return;
  } catch (error) {
    console.error(error);
  }

  showAccessView();
}

initialize();
