function isSupabaseConfigured() {
  const config = window.FEEDBACK_APP_CONFIG || {};
  const publishableKey = config.supabasePublishableKey || config.supabaseAnonKey;
  return Boolean(
    config.supabaseUrl &&
      publishableKey &&
      !config.supabaseUrl.startsWith("__") &&
      !publishableKey.startsWith("__"),
  );
}

function createLocalBackend() {
  function readItems() {
    const stored = localStorage.getItem(storageKeys.localFeedback);
    if (!stored) {
      const legacyStored = localStorage.getItem(storageKeys.legacyLocalFeedback);
      if (legacyStored) {
        try {
          const migratedItems = JSON.parse(legacyStored)
            .filter((item) => !String(item.id).startsWith("demo-"))
            .map((item) => ({
              ...item,
              description: item.description?.trim() || item.title || "",
              kind: "feedback",
            }));
          writeItems(migratedItems);
          return migratedItems;
        } catch {
          // Fall through to an empty board when legacy data cannot be read.
        }
      }

      writeItems([]);
      return [];
    }

    try {
      return JSON.parse(stored);
    } catch {
      writeItems([]);
      return [];
    }
  }

  function writeItems(items) {
    localStorage.setItem(storageKeys.localFeedback, JSON.stringify(items));
  }

  function getVoteValues(item) {
    const voteValues = { ...(item.voteValues || {}) };
    (item.voterIds || []).forEach((userId) => {
      if (!voteValues[userId]) {
        voteValues[userId] = 1;
      }
    });
    return voteValues;
  }

  function normalize(item, userId) {
    const voteValues = getVoteValues(item);
    const userVote = voteValues[userId] || 0;
    return {
      id: item.id,
      kind: item.kind === "bug_report" ? "bug_report" : "feedback",
      description: item.description,
      authorNickname:
        item.authorId === userId
          ? localStorage.getItem(storageKeys.nickname) || item.authorNickname
          : item.authorNickname,
      createdAt: item.createdAt,
      upvoteCount:
        (item.baseVotes || 0) +
        Object.values(voteValues).filter((value) => Number(value) === 1).length,
      downvoteCount: Object.values(voteValues).filter((value) => Number(value) === -1).length,
      userVote,
      isOwner: item.authorId === userId,
    };
  }

  return {
    supportsAdmin: false,

    async hasAccess() {
      return true;
    },

    async verifyAccess() {
      return true;
    },

    async hasAdminAccess() {
      return false;
    },

    async verifyAdminAccess() {
      return false;
    },

    async restoreUser() {
      const nickname = localStorage.getItem(storageKeys.nickname);
      const userId = localStorage.getItem(storageKeys.localUserId);
      return nickname && userId ? { nickname, userId } : null;
    },

    async ensureUser(nickname) {
      let userId = localStorage.getItem(storageKeys.localUserId);
      if (!userId) {
        userId = crypto.randomUUID();
        localStorage.setItem(storageKeys.localUserId, userId);
      }

      const items = readItems();
      let didChangeAuthor = false;
      items.forEach((item) => {
        if (item.authorId === userId && item.authorNickname !== nickname) {
          item.authorNickname = nickname;
          didChangeAuthor = true;
        }
      });
      if (didChangeAuthor) {
        writeItems(items);
      }

      localStorage.setItem(storageKeys.nickname, nickname);
      return { nickname, userId };
    },

    async listFeedback(userId) {
      return readItems().map((item) => normalize(item, userId));
    },

    async createFeedback({ description, kind, nickname, userId }) {
      const items = readItems();
      items.unshift({
        id: crypto.randomUUID(),
        kind,
        description,
        authorNickname: nickname,
        authorId: userId,
        createdAt: new Date().toISOString(),
        baseVotes: 0,
        voteValues: {},
      });
      writeItems(items);
    },

    async deleteFeedback(feedbackId, userId, isAdmin = false) {
      const items = readItems();
      const item = items.find((candidate) => String(candidate.id) === String(feedbackId));
      if (!item || (!isAdmin && item.authorId !== userId)) {
        throw new Error("Feedback cannot be deleted by this user");
      }

      writeItems(items.filter((candidate) => String(candidate.id) !== String(feedbackId)));
    },

    async clearAllFeedback() {
      writeItems([]);
    },

    async setVote(feedbackId, userId, value) {
      const items = readItems();
      const item = items.find((candidate) => String(candidate.id) === String(feedbackId));
      if (!item) {
        throw new Error("Feedback not found");
      }

      item.voteValues = getVoteValues(item);
      delete item.voterIds;
      if (value === 0) {
        delete item.voteValues[userId];
      } else {
        item.voteValues[userId] = value;
      }
      writeItems(items);
    },
  };
}

function createSupabaseBackend() {
  const config = window.FEEDBACK_APP_CONFIG;
  const publishableKey = config.supabasePublishableKey || config.supabaseAnonKey;
  const client = window.supabase.createClient(config.supabaseUrl, publishableKey);

  async function ensureSession() {
    const { data, error } = await client.auth.getSession();
    if (error) {
      throw error;
    }

    if (data.session) {
      return data.session;
    }

    const result = await client.auth.signInAnonymously();
    if (result.error) {
      throw result.error;
    }
    return result.data.session;
  }

  return {
    supportsAdmin: true,

    async hasAccess() {
      await ensureSession();
      const { data, error } = await client.rpc("has_feedback_access");
      if (error) {
        throw error;
      }
      return data === true;
    },

    async verifyAccess(password) {
      await ensureSession();
      const { data, error } = await client.rpc("verify_feedback_password", {
        p_password: password,
      });
      if (error) {
        throw error;
      }
      return data === true;
    },

    async hasAdminAccess() {
      await ensureSession();
      const { data, error } = await client.rpc("has_feedback_admin_access");
      if (error) {
        throw error;
      }
      return data === true;
    },

    async verifyAdminAccess(password) {
      await ensureSession();
      const { data, error } = await client.rpc("verify_feedback_admin_password", {
        p_password: password,
      });
      if (error) {
        throw error;
      }
      return data === true;
    },

    async restoreUser() {
      const session = await ensureSession();
      const userId = session.user.id;

      const { data: profile, error: profileError } = await client
        .from("profiles")
        .select("nickname")
        .eq("id", userId)
        .maybeSingle();
      if (profileError) {
        throw profileError;
      }

      return profile ? { nickname: profile.nickname, userId } : null;
    },

    async ensureUser(nickname) {
      const session = await ensureSession();
      const userId = session.user.id;
      const { error } = await client.from("profiles").upsert({ id: userId, nickname });
      if (error) {
        throw error;
      }

      localStorage.setItem(storageKeys.nickname, nickname);
      return { nickname, userId };
    },

    async listFeedback(userId) {
      const { data, error } = await client
        .from("feedback")
        .select(
          "id,kind,description,author_id,created_at,author:profiles!feedback_author_id_fkey(nickname),votes(user_id,value)",
        );
      if (error) {
        throw error;
      }

      return data.map((item) => {
        const userVote = item.votes.find((vote) => vote.user_id === userId)?.value || 0;
        return {
          id: item.id,
          kind: item.kind,
          description: item.description,
          authorNickname: item.author?.nickname || "Unknown",
          createdAt: item.created_at,
          upvoteCount: item.votes.filter((vote) => vote.value === 1).length,
          downvoteCount: item.votes.filter((vote) => vote.value === -1).length,
          userVote,
          isOwner: item.author_id === userId,
        };
      });
    },

    async createFeedback({ description, kind, userId }) {
      const { error } = await client.from("feedback").insert({
        kind,
        description,
        author_id: userId,
      });
      if (error) {
        throw error;
      }
    },

    async deleteFeedback(feedbackId, userId, isAdmin = false) {
      let query = client.from("feedback").delete().eq("id", feedbackId);
      if (!isAdmin) {
        query = query.eq("author_id", userId);
      }

      const { data, error } = await query.select("id").maybeSingle();
      if (error) {
        throw error;
      }
      if (!data) {
        throw new Error("Feedback cannot be deleted by this user");
      }
    },

    async clearAllFeedback() {
      const { error } = await client.rpc("clear_all_feedback");
      if (error) {
        throw error;
      }
    },

    async setVote(feedbackId, userId, value) {
      if (value !== 0) {
        const { error } = await client.from("votes").upsert(
          {
            feedback_id: feedbackId,
            user_id: userId,
            value,
          },
          { onConflict: "feedback_id,user_id" },
        );
        if (error) {
          throw error;
        }
        return;
      }

      const { error } = await client
        .from("votes")
        .delete()
        .eq("feedback_id", feedbackId)
        .eq("user_id", userId);
      if (error) {
        throw error;
      }
    },
  };
}

